"""Generate the V3 results section for docs/06_results.md from saved run summaries (read-only).

Written before any V3 test result existed. Covers the frozen hypotheses (via v3_decide) and every prespecified
descriptive analysis in docs/05_protocol.md. For the test split it uses exactly one run per command.

    uv run python scripts/v3_results.py results/v3 --split test
    uv run python scripts/v3_results.py results/v3 --split val --latest
"""

import argparse
from pathlib import Path

from v3_decide import decide, load, num, to_markdown

REGIONS = [("Home", None), ("Bornholm", "bornholm"), ("Skagen", "skagen"), ("Salish Sea", "salish_sea"),
           ("Houston", "houston")]


def n0(x: float) -> str:
    return f"{x:,.0f}"


def ci(x: dict | None) -> str:
    if x is None:
        return "not computed"
    return f"{num(x['mean'])} ({num(x['ci95_lo'])} to {num(x['ci95_hi'])})"


def coverage_cell(iv: dict, level: str, horizon: str) -> str:
    x = iv["intervals"][level][horizon]
    return f"{x['coverage']:.1%} ({x['ci95_lo']:.1%}–{x['ci95_hi']:.1%})"


def width_cell(iv: dict, level: str, horizon: str) -> str:
    x = iv["intervals"][level][horizon]
    return f"{n0(x['half_width_along_m'])} / {n0(x['half_width_cross_m'])}"


def error_cell(m: dict, model: str) -> str:
    return f"{n0(m[model]['err_20min_m']['mean'])} / {n0(m[model]['fde_m']['mean'])}"


def pct(x: float) -> str:
    return f"{x:+.1%}".replace("-", "\u2212")


def relative(m: dict, metric: str) -> float:
    return m["E_fairway"][metric]["mean"] / m["A_motion"][metric]["mean"] - 1


def section(results: Path, split: str, latest: bool) -> str:
    gbm = {name: load(results, f"gbm_{split}" if r is None else f"gbm_transfer_{split}_{r}", latest)[0]
           for name, r in REGIONS}

    def intervals(fs, r, local):
        name = split if r is None else f"transfer_{split}_{r}" + ("_localcal" if local else "")
        return load(results, f"intervals_{fs}_{name}", latest)[0]

    title = "V3 TEST RESULTS: single run after the V3 freeze" if split == "test" else \
        "V3 VALIDATION RESULTS (regenerated by scripts/v3_results.py)"
    period = "16–29 Oct" if split == "test" else "7–11 Oct"
    out = [f"# {title}", "",
           f"Evaluated days: {period} (2026 for Danish regions, 2025 for US regions). Models trained on the Danish "
           "home area, 19 Sep–6 Oct 2026; prediction boxes calibrated on 12–15 Oct (home, or the region's own days "
           "for local calibration). Seed 0. Confidence intervals are paired and vessel-grouped.", ""]

    out += ["## Hypotheses", "", to_markdown(decide(results, split, latest)).split("\n", 2)[2].strip(), ""]

    out += ["## Point forecasts: mean error at 20 / 60 minutes (m)", "",
            "| Setting | Windows | CV | A motion | C raw location | E fairway | F vessel + fairway |",
            "|---|---:|---:|---:|---:|---:|---:|"]
    for name, r in gbm.items():
        if r is None:
            out.append(f"| {name} | missing | | | | | |")
            continue
        m = r["metrics"]
        out.append(f"| {name} | {m['cv']['fde_m']['n_samples']:,} | "
                   + " | ".join(error_cell(m, k) for k in ("cv", "A_motion", "C_location", "E_fairway",
                                                           "F_all_fairway")) + " |")
    out += ["", "Paired differences (m, 95% CI; negative = first model better) and E's relative change against A:", "",
            "| Setting | E − A, 20 min | E − A, 60 min | C − A, 20 min | C − A, 60 min | E vs A, 20 / 60 min |",
            "|---|---|---|---|---|---|"]
    for name, r in gbm.items():
        if r is None:
            continue
        p, m = r["paired"], r["metrics"]
        out.append(f"| {name} | {ci(p['E_fairway - A_motion'].get('err_20min_m'))} | "
                   f"{ci(p['E_fairway - A_motion']['fde_m'])} | {ci(p['C_location - A_motion'].get('err_20min_m'))} | "
                   f"{ci(p['C_location - A_motion']['fde_m'])} | {pct(relative(m, 'err_20min_m'))} / "
                   f"{pct(relative(m, 'fde_m'))} |")
    home = gbm["Home"]
    if home:
        m = home["metrics"]
        out += ["", "Home area, raw location vs fairway (descriptive, mean difference E − C): "
                f"{num(m['E_fairway']['err_20min_m']['mean'] - m['C_location']['err_20min_m']['mean'])} m at 20 min, "
                f"{num(m['E_fairway']['fde_m']['mean'] - m['C_location']['fde_m']['mean'])} m at 60 min."]

    h = gbm["Houston"]
    if h:
        rows = {g["ship_group"]: g for g in h["fde_by_ship_group"]}
        merch = [rows[k] for k in ("cargo", "tanker") if k in rows]
        nm = sum(x["n"] for x in merch)
        wm = lambda k: sum(x["n"] * x[k] for x in merch) / nm  # noqa: E731
        out += ["", "## Houston (descriptive): mean error at 60 minutes by ship group (m)", "",
                "| Group | Windows | CV | A motion | E fairway |", "|---|---:|---:|---:|---:|"]
        out += [f"| {g['ship_group']} | {g['n']:,} | {n0(g['cv'])} | {n0(g['A_motion'])} | {n0(g['E_fairway'])} |"
                for g in h["fde_by_ship_group"]]
        if nm:
            out.append(f"| merchant (cargo + tanker) | {nm:,} | {n0(wm('cv'))} | {n0(wm('A_motion'))} | "
                       f"{n0(wm('E_fairway'))} |")

    out += ["", "## Prediction boxes: coverage (model E)", "",
            "Marginal empirical coverage over all windows of a setting (95% CI, vessel bootstrap).", "",
            "| Setting | Calibration | 80% box, 20 min | 80% box, 60 min | 90% box, 20 min | 90% box, 60 min |",
            "|---|---|---|---|---|---|"]
    for name, r in REGIONS:
        for local in ((False,) if r is None else (False, True)):
            iv = intervals("E_fairway", r, local)
            label = "local" if local else "home"
            if iv is None:
                out.append(f"| {name} | {label} | missing | | | |")
                continue
            out.append(f"| {name} | {label} | " + " | ".join(
                coverage_cell(iv, lvl, hz) for lvl in ("0.8", "0.9") for hz in ("20", "60")) + " |")

    out += ["", "## Prediction boxes: half-widths along / cross-track (m)", "",
            "Local calibration for the independent waterways, home calibration for the home area.", "",
            "| Setting | Model | 80% box, 20 min | 80% box, 60 min | 90% box, 20 min | 90% box, 60 min |",
            "|---|---|---|---|---|---|"]
    for name, r in REGIONS:
        for fs, label in (("E_fairway", "E"), ("A_motion", "A")):
            iv = intervals(fs, r, r is not None)
            if iv is None:
                out.append(f"| {name} | {label} | missing | | | |")
                continue
            out.append(f"| {name} | {label} | " + " | ".join(
                width_cell(iv, lvl, hz) for lvl in ("0.8", "0.9") for hz in ("20", "60")) + " |")
    out += ["", "Coverage shows whether the boxes are honest, not whether they are narrow enough to be useful.", ""]
    if split == "test":
        out.append("In the test evaluation the calibration days (12–15 Oct) precede the evaluated days (16–29 Oct), as "
                   "they would in deployment.")
    else:
        out.append("In validation the calibration days (12–15 Oct) follow the evaluated days (7–11 Oct).")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("results", type=Path)
    ap.add_argument("--split", default="test", choices=["val", "test"])
    ap.add_argument("--latest", action="store_true", help="validation checks only")
    args = ap.parse_args(argv)
    if args.split == "test" and args.latest:
        raise SystemExit("--latest is not allowed for the test split")
    print(section(args.results, args.split, args.latest))


if __name__ == "__main__":
    main()
